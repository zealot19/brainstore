"""Backend-aware helper to convert an integer surrogate PK to a UUID PK.

Postgres has no bigint→uuid cast, so the autogenerated
`ALTER COLUMN id TYPE uuid USING id::uuid` fails there (it only worked on SQLite,
which rebuilds the table). This converts the PK safely on both backends:
- Postgres: drop the bigint `id`, add a `uuid` `id` (gen_random_uuid(), PG13+).
  Association rows are preserved (only the surrogate key changes); safe for leaf
  tables that nothing references by id.
- SQLite: rebuild the table via the schema editor (used by the test DB).
The Django migration *state* becomes a UUIDField in both cases.
"""
import uuid

from django.db import migrations, models


def _pg_forwards(table):
    def fn(apps, schema_editor):
        if schema_editor.connection.vendor != "postgresql":
            return
        q = schema_editor.execute
        q(f'ALTER TABLE "{table}" DROP CONSTRAINT "{table}_pkey" CASCADE')
        q(f'ALTER TABLE "{table}" DROP COLUMN "id"')
        q(f'ALTER TABLE "{table}" ADD COLUMN "id" uuid DEFAULT gen_random_uuid() NOT NULL')
        q(f'ALTER TABLE "{table}" ADD PRIMARY KEY ("id")')
    return fn


def _sqlite_forwards(app_label, model_name):
    def fn(apps, schema_editor):
        if schema_editor.connection.vendor == "postgresql":
            return
        model = apps.get_model(app_label, model_name)
        old = model._meta.get_field("id")   # historical (bound) BigAutoField
        new = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False, serialize=False)
        new.set_attributes_from_name("id")
        new.model = model
        schema_editor.alter_field(model, old, new)
    return fn


def int_pk_to_uuid(app_label, model_name, table):
    """A migration operation that turns `table`'s integer PK into a UUID PK."""
    return migrations.SeparateDatabaseAndState(
        state_operations=[
            migrations.AlterField(
                model_name=model_name,
                name="id",
                field=models.UUIDField(primary_key=True, default=uuid.uuid4,
                                       editable=False, serialize=False,
                                       verbose_name="identifiant"),
            ),
        ],
        database_operations=[
            migrations.RunPython(_pg_forwards(table), migrations.RunPython.noop),
            migrations.RunPython(_sqlite_forwards(app_label, model_name), migrations.RunPython.noop),
        ],
    )
